-- Legacy single-sense glosses may contain literal semicolons. Multi-sense
-- glosses use escaped full-width semicolons and backslashes (word-senses.ts).
CREATE OR REPLACE FUNCTION wordmate.resolved_word_pos(headword text, labels text, gloss text)
RETURNS text LANGUAGE plpgsql IMMUTABLE STRICT AS $$
DECLARE
  parts text[];
  meanings text[];
  corrected text;
  i integer;
BEGIN
  labels := wordmate.short_word_pos(labels);
  labels := regexp_replace(labels, '(auxiliary v\.|助动词|助v\.)', 'aux.', 'gi');
  labels := regexp_replace(labels, '(modal v\.|情态动词|情态v\.)', 'mod.', 'gi');
  labels := regexp_replace(labels, '(限定词|determiner)', 'det.', 'gi');
  labels := regexp_replace(labels, '\mparticle\M|助词', 'part.', 'gi');
  labels := regexp_replace(labels, '\mcontraction\M|缩约形式', 'contr.', 'gi');
  parts := string_to_array(labels, '；');
  IF NOT ('教材' = ANY(parts)) THEN RETURN labels; END IF;
  IF labels = '教材' THEN
    RETURN coalesce(wordmate.textbook_word_pos(headword, gloss), labels);
  END IF;
  SELECT array_agg(regexp_replace(match[1], '\\([；\\])', '\1', 'g') ORDER BY ord)
    INTO meanings
    FROM regexp_matches(gloss, '((?:[^；\\]|\\.)+)', 'g') WITH ORDINALITY AS chunks(match, ord);
  IF cardinality(meanings) IS DISTINCT FROM cardinality(parts) THEN RETURN labels; END IF;
  FOR i IN 1..cardinality(parts) LOOP
    IF parts[i] = '教材' THEN
      corrected := wordmate.textbook_word_pos(headword, meanings[i]);
      IF corrected IS NOT NULL THEN parts[i] := corrected; END IF;
    END IF;
  END LOOP;
  RETURN array_to_string(parts, '；');
END $$;

UPDATE wordmate.child_words
SET part_of_speech = wordmate.resolved_word_pos(lemma, part_of_speech, meaning_zh)
WHERE part_of_speech <> wordmate.resolved_word_pos(lemma, part_of_speech, meaning_zh);

UPDATE wordmate.shared_wordbook_items
SET part_of_speech = wordmate.resolved_word_pos(lemma, part_of_speech, meaning_zh)
WHERE part_of_speech <> wordmate.resolved_word_pos(lemma, part_of_speech, meaning_zh);

-- Also covers previously prepared imports and legacy writers during rollback.
CREATE OR REPLACE FUNCTION wordmate.normalize_word_pos() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.part_of_speech := wordmate.resolved_word_pos(NEW.lemma, NEW.part_of_speech, NEW.meaning_zh);
  RETURN NEW;
END $$;
